/**
 * Build a concrete conditional revert.sql from an activation folder:
 *   activations/<id>/backup-pre.json  (immutable copy)
 *   activations/<id>/backup-post.json (in-transaction capture)
 *
 * Validates post vs approved-manifest (identity + name/colors/maps/images/shared/
 * availability/archive). Missing required fields → STOP (no manifest fallback).
 *
 * Usage:
 *   node build-revert-from-backup.mjs --activation-dir activations/<id>
 *   node build-revert-from-backup.mjs --post path/to/backup-post.json --pre path/to/backup-pre.json
 *
 * Output (write-once): <activation-dir>/revert-from-backup.sql
 *   or --out path
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { validatePostAgainstApproved } from "./h29-post-validate.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);

function argVal(flag) {
  const i = args.indexOf(flag);
  return i >= 0 ? args[i + 1] : null;
}

const activationDir = argVal("--activation-dir");
const postPath = activationDir
  ? join(resolve(activationDir), "backup-post.json")
  : argVal("--post") || join(__dirname, "results", "backup-post.json");
const prePath = activationDir
  ? join(resolve(activationDir), "backup-pre.json")
  : argVal("--pre") || join(__dirname, "backup-pre.json");
const outPath =
  argVal("--out") ||
  (activationDir
    ? join(resolve(activationDir), "revert-from-backup.sql")
    : join(__dirname, "results", "revert-from-backup.sql"));

const approvedPath = join(__dirname, "approved-manifest.json");

if (!existsSync(postPath)) {
  console.error(`STOP: missing post backup at ${postPath}`);
  process.exit(1);
}
if (!existsSync(prePath)) {
  console.error(`STOP: missing pre backup at ${prePath}`);
  process.exit(1);
}
if (existsSync(outPath)) {
  console.error(
    `STOP: refuse to overwrite existing revert at ${outPath} (immutable activation artifacts)`,
  );
  process.exit(1);
}

const pre = JSON.parse(readFileSync(prePath, "utf8"));
const post = JSON.parse(readFileSync(postPath, "utf8"));
const approved = JSON.parse(readFileSync(approvedPath, "utf8"));

const check = validatePostAgainstApproved(post, pre, approved);
if (!check.ok) {
  console.error("STOP: post-state does not match approved result — refuse to generate revert:");
  for (const e of check.errors) console.error(" -", e);
  process.exit(1);
}

function q(s) {
  if (s === null || s === undefined) return "null";
  return `'${String(s).replaceAll("'", "''")}'`;
}

function textArr(arr) {
  if (!Array.isArray(arr)) {
    throw new Error("textArr requires array (no fallback)");
  }
  return `array[${arr.map(q).join(",")}]::text[]`;
}

function jsonb(v) {
  if (v === null || v === undefined) {
    throw new Error("jsonb requires value (no fallback)");
  }
  return `${q(JSON.stringify(v))}::jsonb`;
}

function ts(v) {
  if (v === null || v === undefined) {
    throw new Error("post updated_at is required and must not be null");
  }
  return `${q(v)}::timestamptz`;
}

const postTargetImages = post.target.images;
const postTargetShared = post.target.shared_image_urls;
const postTargetMap = post.target.color_image_map;
const postTargetColors = post.target.color_ids;

const sql = `-- H29 CONCRETE REVERT — generated by build-revert-from-backup.mjs
-- Restores exact pre values from this activation's backup-pre.json.
-- Conditioned on exact post capture (updated_at + images + shared + map).
-- Later edit / mismatch → exception → FULL rollback (no partial writes).
-- Generated: ${new Date().toISOString()}
-- Post source: ${postPath}

begin;

do $$
declare
  t public.products%rowtype;
  s082 public.products%rowtype;
  s071 public.products%rowtype;
  target_id uuid := ${q(pre.target.id)};
  source_082 uuid := ${q(pre.source082.id)};
  source_071 uuid := ${q(pre.source071.id)};
  expected_post_images text[] := ${textArr(postTargetImages)};
  expected_post_shared jsonb := ${jsonb(postTargetShared)};
  expected_post_map jsonb := ${jsonb(postTargetMap)};
  expected_post_colors text[] := ${textArr(postTargetColors)};
  post_target_updated_at timestamptz := ${ts(post.target.updated_at)};
  post_082_updated_at timestamptz := ${ts(post.source082.updated_at)};
  post_071_updated_at timestamptz := ${ts(post.source071.updated_at)};
begin
  select * into t from public.products where id = target_id for update;
  select * into s082 from public.products where id = source_082 for update;
  select * into s071 from public.products where id = source_071 for update;

  if t.id is null or s082.id is null or s071.id is null then
    raise exception 'H29 revert: missing row';
  end if;

  if t.name is distinct from ${q(approved.target.name)}
     or t.sku is distinct from ${q(pre.target.sku)}
     or t.slug is distinct from ${q(pre.target.slug)}
     or t.price is distinct from ${q(pre.target.price)}
     or t.in_stock is distinct from ${pre.target.in_stock}
     or t.stock_quantity is distinct from null
     or t.packaging is distinct from ${jsonb(pre.target.packaging)}
     or t.color_ids is distinct from expected_post_colors
     or t.color_image_map is distinct from expected_post_map
     or coalesce(t.unavailable_color_ids, '{}'::text[]) is distinct from '{}'::text[]
     or t.images is distinct from expected_post_images
     or t.shared_image_urls is distinct from expected_post_shared
     or t.archived_at is not null
     or t.redirect_to_product_id is not null
     or t.updated_at is distinct from post_target_updated_at
  then
    raise exception 'H29 revert: target post-state guard mismatch (later edit?)';
  end if;

  if s082.archived_at is null
     or s082.redirect_to_product_id is distinct from target_id
     or s082.sku is distinct from ${q(pre.source082.sku)}
     or s082.images is distinct from ${textArr(pre.source082.images)}
     or s082.updated_at is distinct from post_082_updated_at
  then
    raise exception 'H29 revert: source 082 post-state guard mismatch';
  end if;

  if s071.archived_at is null
     or s071.redirect_to_product_id is distinct from target_id
     or s071.sku is distinct from ${q(pre.source071.sku)}
     or s071.images is distinct from ${textArr(pre.source071.images)}
     or s071.updated_at is distinct from post_071_updated_at
  then
    raise exception 'H29 revert: source 071 post-state guard mismatch';
  end if;

  update public.products
     set name = ${q(pre.target.name)},
         color_ids = ${textArr(pre.target.color_ids)},
         color_image_map = ${jsonb(pre.target.color_image_map)},
         images = ${textArr(pre.target.images)},
         shared_image_urls = ${jsonb(pre.target.shared_image_urls)},
         unavailable_color_ids = ${textArr(pre.target.unavailable_color_ids)},
         archived_at = null,
         redirect_to_product_id = null,
         updated_at = now()
   where id = target_id;

  update public.products
     set archived_at = null,
         redirect_to_product_id = null,
         updated_at = now()
   where id = source_082;

  update public.products
     set archived_at = null,
         redirect_to_product_id = null,
         updated_at = now()
   where id = source_071;

  raise notice 'H29 revert: OK — exact pre-merge restored from backup-pre';
end $$;

commit;
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, sql, "utf8");
console.log("Wrote", outPath);
